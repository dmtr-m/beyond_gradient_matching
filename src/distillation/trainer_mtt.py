import logging
import os
import random

import mlflow
import torch
import torch.nn.functional as F
from torch.cuda import amp
from tqdm import trange

from coreset import CoresetModule
from data import DataModule
from evaluator import Evaluator
from generator import GeneratorModel
from learner import LearnerModel
from utils import average, batch_to_cuda, configure_optimizer, endless_dataloader

from .trainer_base import TrainerBase

logger = logging.getLogger(__name__)


class TrainerMTT(TrainerBase):
    """
    Trajectory matching trainer (MTT) for DiLM.

    Expert trajectories are pre-generated by generate_buffer.py: each is a list
    of param-snapshot dicts produced by training the learner on real data for
    train_epochs epochs.  During optimisation the generator is trained so that
    simulating `mtt_syn_steps` gradient steps of the learner on *synthetic* text
    (weighted by the generator's own per-sample loss) moves the learner's
    parameters toward the same target the expert reached.

    Gradient flow:
        MTT loss → unrolled learner steps → loss_weights → generator.compute_loss
        → generator parameters
    """

    def fit(
        self,
        generator: GeneratorModel,
        learner: LearnerModel,
        data_module: DataModule,
        evaluator: Evaluator,
        repset_teachers,
        coreset_module: CoresetModule,
    ):
        generator.cuda()
        learner.cuda()

        num_labels = data_module.num_labels

        assert self.config.total_train_step % self.config.inner_loop == 0
        outer_loop = self.config.total_train_step // self.config.inner_loop

        # Load expert buffer
        buffer, expert_files, file_idx, expert_idx = self._load_buffer()

        # Synthetic data loaders (regenerated periodically)
        gm_syn_loaders = self._get_gm_syn_loaders(generator, learner, data_module)

        # Optional LM regularisation loader
        lm_loader = None
        if self.config.lm_lambda > 0:
            lm_loader = endless_dataloader(
                data_module.get_train_loader(batch_size=self.config.lm_batch_size),
                max_iteration=self.config.total_train_step,
            )

        # Generator optimiser
        optimizer, scheduler = self.generator_optimizer(generator)
        scaler = amp.GradScaler(enabled=self.use_amp)

        # Learnable inner-loop learning rate (optimised jointly with generator)
        syn_lr = torch.tensor(
            self.config.mtt_syn_lr, dtype=torch.float32, device="cuda"
        )
        if self.config.mtt_train_syn_lr:
            syn_lr = syn_lr.requires_grad_(True)
            optimizer.add_param_group(
                {"params": [syn_lr], "lr": self.config.lr * 10, "weight_decay": 0.0}
            )

        best_ckpt_path = os.path.join(self.config.save_model_dir, "best-ckpt")
        tokenizer_path = os.path.join(self.config.save_model_dir, "tokenizer")
        generator.save_tokenizer(tokenizer_path)

        train_logs = []
        best_val_score = float("-inf")
        logger.info("Start MTT training!")

        for ol in trange(outer_loop, dynamic_ncols=True, leave=False, desc="Outer loop"):
            train_step = ol * self.config.inner_loop

            # Validation
            if (
                train_step % self.config.val_interval == 0
                and train_step >= self.config.val_skip_step
            ):
                results = self.evaluate(
                    generator, learner, evaluator, data_module, coreset_module,
                    step=train_step,
                )
                if results[f"valid.{evaluator.metric_key}"] > best_val_score:
                    best_val_score = results[f"valid.{evaluator.metric_key}"]
                    generator.save_model(best_ckpt_path)
                    logger.info(f"Saved best checkpoint at '{best_ckpt_path}'")

            # Regenerate synthetic data periodically
            if ol % self.config.generate_dataset_interval == 0:
                logger.info(
                    "TRAIN [{}/{}]: Regenerating synthetic data".format(
                        train_step, self.config.total_train_step
                    )
                )
                gm_syn_loaders = self._get_gm_syn_loaders(generator, learner, data_module)

            generator.train()
            outer_step_logs = []

            for _ in range(self.config.inner_loop):
                # ── sample expert trajectory ──────────────────────────────────
                expert_traj, buffer, file_idx, expert_idx = self._sample_trajectory(
                    buffer, expert_files, file_idx, expert_idx
                )
                start_epoch = random.randint(0, self.config.mtt_max_start_epoch)
                starting_snap = expert_traj[start_epoch]
                target_snap = expert_traj[start_epoch + self.config.mtt_expert_epochs]

                target_flat = self._flatten_params(target_snap).cuda()
                starting_flat = self._flatten_params(starting_snap).cuda()
                num_params = target_flat.numel()

                # ── unroll learner on synthetic data ─────────────────────────
                student_params = [starting_flat.detach().clone().requires_grad_(True)]

                for _ in range(self.config.mtt_syn_steps):
                    label = random.randint(0, num_labels - 1)
                    batch = next(gm_syn_loaders[label])

                    with amp.autocast(enabled=self.use_amp, dtype=self.amp_dtype):
                        # Generator loss provides the link back to generator weights
                        gen_losses = generator.compute_loss(
                            **batch_to_cuda(batch["generator"])
                        )
                        loss_weights = F.softmax(
                            -gen_losses / self.config.normalize_temperature, dim=-1
                        )

                        loss = self._weighted_learner_loss(
                            learner, student_params[-1], starting_snap,
                            batch_to_cuda(batch["learner"]), loss_weights,
                        )

                    grad = torch.autograd.grad(
                        loss, student_params[-1], create_graph=True
                    )[0]
                    student_params.append(student_params[-1] - syn_lr * grad)

                # ── MTT loss ─────────────────────────────────────────────────
                with amp.autocast(enabled=self.use_amp, dtype=self.amp_dtype):
                    param_loss = (
                        F.mse_loss(student_params[-1], target_flat, reduction="sum")
                        / num_params
                    )
                    param_dist = (
                        F.mse_loss(starting_flat, target_flat, reduction="sum")
                        / num_params
                    ).clamp(min=1e-6)
                    loss_mtt = param_loss / param_dist

                    if lm_loader is not None:
                        loss_lm = generator.compute_loss(
                            **batch_to_cuda(next(lm_loader)["generator"])
                        ).mean()
                        total_loss = (
                            loss_mtt * (1 - self.config.lm_lambda)
                            + loss_lm * self.config.lm_lambda
                        )
                    else:
                        loss_lm = 0.0
                        total_loss = loss_mtt

                scaler.scale(total_loss).backward()
                self.train_step(generator, optimizer, scheduler, scaler)

                outer_step_logs.append({
                    "train.loss_mtt": loss_mtt.item(),
                    "train.param_loss": param_loss.item(),
                    "train.param_dist": param_dist.item(),
                    "train.loss_lm": loss_lm if isinstance(loss_lm, float) else loss_lm.item(),
                    "train.syn_lr": syn_lr.item(),
                })

                # Free the unrolled computation graph
                del student_params

            train_logs.append(average(outer_step_logs))

            if ((ol + 1) * self.config.inner_loop) % self.config.log_interval == 0:
                train_logs = average(train_logs)
                train_logs["train.lr"] = scheduler.get_last_lr()[0]
                mlflow.log_metrics(train_logs, step=(ol + 1) * self.config.inner_loop)
                logger.info(
                    "TRAIN [{:>{}}/{}]: {}".format(
                        (ol + 1) * self.config.inner_loop,
                        len(str(self.config.total_train_step)),
                        self.config.total_train_step,
                        train_logs,
                    )
                )
                train_logs = []

        # Final evaluation
        results = self.evaluate(
            generator, learner, evaluator, data_module, coreset_module,
            step=self.config.total_train_step,
        )
        if results[f"valid.{evaluator.metric_key}"] > best_val_score:
            generator.save_model(best_ckpt_path)
            logger.info(f"Saved best checkpoint at '{best_ckpt_path}'")

        last_ckpt_path = os.path.join(self.config.save_model_dir, "last-ckpt")
        generator.save_model(last_ckpt_path)
        logger.info(f"Saved last checkpoint at '{last_ckpt_path}'")
        generator.load_model(best_ckpt_path)
        logger.info("MTT training finished.")

    # ── helpers ──────────────────────────────────────────────────────────────

    def _flatten_params(self, snap: dict[str, torch.Tensor]) -> torch.Tensor:
        """Concatenate param snapshot into a single 1-D vector (CPU)."""
        return torch.cat([p.reshape(-1) for p in snap.values()], dim=0)

    def _unflatten_params(
        self,
        flat: torch.Tensor,
        reference: dict[str, torch.Tensor],
    ) -> dict[str, torch.Tensor]:
        """Restore a flat vector to a name→tensor dict matching reference shapes."""
        out = {}
        offset = 0
        for name, ref in reference.items():
            numel = ref.numel()
            out[name] = flat[offset : offset + numel].reshape(ref.shape)
            offset += numel
        return out

    def _weighted_learner_loss(
        self,
        learner: LearnerModel,
        flat_student: torch.Tensor,
        reference_snap: dict[str, torch.Tensor],
        batch: dict[str, torch.Tensor],
        loss_weights: torch.Tensor,
    ) -> torch.Tensor:
        """
        Forward-pass the learner with `flat_student` parameters (via functional_call)
        and return the loss_weights-weighted cross-entropy.

        If classifier_only is True, only the classifier params come from
        flat_student; the rest are taken from the learner's current state.
        """
        if self.config.mtt_classifier_only:
            # Build a full param dict: frozen backbone + differentiable classifier
            classifier_names = set(learner.classifier_param_names())
            reference_classifier = {
                k: v for k, v in reference_snap.items() if k in classifier_names
            }
            unflat_classifier = self._unflatten_params(flat_student, reference_classifier)

            params = {}
            for name, param in learner.named_parameters():
                if name in classifier_names:
                    params[name] = unflat_classifier[name].to(param.device)
                else:
                    params[name] = param
            buffers = dict(learner.named_buffers())
        else:
            params = self._unflatten_params(flat_student, reference_snap)
            params = {k: v.to(next(learner.parameters()).device) for k, v in params.items()}
            buffers = dict(learner.named_buffers())

        input_ids = batch["input_ids"]
        kwargs = {k: v for k, v in batch.items() if k != "input_ids"}

        outputs = torch.func.functional_call(
            learner, (params, buffers), args=input_ids, kwargs=kwargs
        )
        loss = outputs.loss  # (batch_size,)
        assert loss.shape == loss_weights.shape, f"{loss.shape} vs {loss_weights.shape}"
        return loss.dot(loss_weights)

    def _get_gm_syn_loaders(
        self,
        generator: GeneratorModel,
        learner: LearnerModel,
        data_module: DataModule,
    ) -> dict[int, object]:
        """Generate a fresh synthetic dataset and return per-label endless loaders."""
        from datasets import concatenate_datasets

        syn_datasets = generator.generate_dataset(
            dpc=self.config.gm_syn_dpc,
            n=self.config.inner_loop * self.config.generate_dataset_interval,
        )
        preprocessed = data_module.preprocess_dataset(concatenate_datasets(syn_datasets))

        return {
            label: iter(
                data_module.get_train_loader(
                    dataset=preprocessed,
                    batch_size=self.config.gm_syn_dpc,
                    shuffle=False,
                    drop_last=False,
                    label=label,
                )
            )
            for label in range(data_module.num_labels)
        }

    # ── buffer loading ────────────────────────────────────────────────────────

    def _load_buffer(self):
        """
        Discover and (optionally) load all replay_buffer_*.pt files.
        Returns (buffer, expert_files, file_idx, expert_idx).
        """
        buf_dir = self.config.mtt_buffer_path
        if not os.path.isdir(buf_dir):
            raise FileNotFoundError(
                f"Expert buffer directory not found: '{buf_dir}'. "
                "Run src/distillation/generate_buffer.py first."
            )

        expert_files = sorted(
            [
                os.path.join(buf_dir, f)
                for f in os.listdir(buf_dir)
                if f.startswith("replay_buffer_") and f.endswith(".pt")
            ]
        )
        if not expert_files:
            raise FileNotFoundError(f"No replay_buffer_*.pt files found in '{buf_dir}'")

        if self.config.mtt_load_all:
            buffer = []
            for fp in expert_files:
                buffer.extend(torch.load(fp, weights_only=False))
            random.shuffle(buffer)
            logger.info(f"Loaded {len(buffer)} expert trajectories into RAM")
            return buffer, expert_files, 0, 0
        else:
            random.shuffle(expert_files)
            buffer = torch.load(expert_files[0], weights_only=False)
            random.shuffle(buffer)
            logger.info(
                f"Found {len(expert_files)} buffer file(s). "
                f"Streaming, first file has {len(buffer)} trajectories."
            )
            return buffer, expert_files, 0, 0

    def _sample_trajectory(self, buffer, expert_files, file_idx, expert_idx):
        """
        Return next trajectory (round-robin through files when streaming).
        Also validates that the trajectory has enough epochs for the configured span.
        """
        min_len = self.config.mtt_max_start_epoch + self.config.mtt_expert_epochs + 1

        if self.config.mtt_load_all:
            traj = buffer[random.randint(0, len(buffer) - 1)]
        else:
            traj = buffer[expert_idx]
            expert_idx += 1
            if expert_idx >= len(buffer):
                expert_idx = 0
                file_idx = (file_idx + 1) % len(expert_files)
                buffer = torch.load(expert_files[file_idx], weights_only=False)
                random.shuffle(buffer)
                logger.info(f"Loaded next buffer file: {expert_files[file_idx]}")

        if len(traj) < min_len:
            raise ValueError(
                f"Trajectory has {len(traj)} snapshots but need at least {min_len} "
                f"(mtt_max_start_epoch={self.config.mtt_max_start_epoch} + "
                f"mtt_expert_epochs={self.config.mtt_expert_epochs} + 1). "
                "Re-generate buffer with more train_epochs."
            )

        return traj, buffer, file_idx, expert_idx
